def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--user", default="demo", help="数据归属的用户名")
    ap.add_argument("--clear", action="store_true", help="先删除该用户已有事件")
    args = ap.parse_args()

    db_path = apppaths.app_base_dir() / "data" / "app.db"
    if not db_path.exists():
        sys.exit(f"数据库不存在：{db_path}（先启动一次程序完成初始化）")

    conn = sqlite3.connect(db_path)
    conn.row_factory = sqlite3.Row
    row = conn.execute("SELECT id FROM users WHERE username=?", (args.user,)).fetchone()
    if not row:
        sys.exit(f"用户不存在：{args.user}")
    uid = row["id"]

    if args.clear:
        n = conn.execute("DELETE FROM events WHERE user_id=?", (uid,)).rowcount
        print(f"已清空 {n} 条事件")

    have = {r[0] for r in conn.execute("SELECT title FROM events WHERE user_id=?", (uid,))}
    stamp = datetime.now().isoformat(timespec="seconds")
    added = 0
    for ev in EVENTS:
        title = ev[0]
        if title in have:
            continue
        title_, era, year, year_end, place, people, cause, process, impact, signif, tags = ev
        conn.execute(
            "INSERT INTO events(user_id,uuid,title,era,year,year_end,year_label,place,people,"
            "cause,process,impact,significance,tags,created_at)"
            " VALUES(?,?,?,?,?,?,?,?,?,?,?,?,?,?,?)",
            (
                uid,
                uuid.uuid4().hex,
                title_,
                era,
                year,
                year_end,
                "",
                place,
                people,
                cause,
                process,
                impact,
                signif,
                tags,
                stamp,
            ),
        )
        added += 1
    conn.commit()
    total = conn.execute("SELECT COUNT(*) FROM events WHERE user_id=?", (uid,)).fetchone()[0]
    conn.close()
    print(f"新增 {added} 条，{args.user} 现有事件 {total} 条")


if __name__ == "__main__":
    main()
